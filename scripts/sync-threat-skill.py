#!/usr/bin/env python3
"""Synchronize the repository's AgentSec skill from Claude to Codex."""

import argparse
import json
from pathlib import Path


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    source = root / ".claude/skills/update-threat-db"
    target = root / ".agents/skills/update-threat-db"
    skill = (source / "SKILL.md").read_text()
    scenarios = json.loads((source / "evals/scenarios.json").read_text())
    assert skill.startswith("---\nname: update-threat-db\n")
    assert scenarios["skill"] == "update-threat-db"
    assert len(scenarios["positive"]) >= 8 and len(scenarios["negative"]) >= 2
    drift = []
    for relative in ("SKILL.md", "evals/scenarios.json"):
        expected = (source / relative).read_bytes()
        destination = target / relative
        if args.write:
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_bytes(expected)
        if not destination.is_file() or destination.read_bytes() != expected:
            drift.append(str(destination.relative_to(root)))
    legacy = root / ".agents/skills/ccguide/update-threat-db.md"
    legacy_text = (
        "# Update threat database\n\n"
        "This compatibility entry delegates to the native `update-threat-db` skill.\n"
        "Read `.agents/skills/update-threat-db/SKILL.md` from the guide root, then\n"
        "execute its AgentSec workflow. Do not edit the guide database first.\n\n"
        "Generated by `scripts/sync-threat-skill.py`; edit the canonical skill in\n"
        "`.claude/skills/update-threat-db/` and regenerate both consumers.\n"
    ).encode()
    if args.write:
        legacy.parent.mkdir(parents=True, exist_ok=True)
        legacy.write_bytes(legacy_text)
    if not legacy.is_file() or legacy.read_bytes() != legacy_text:
        drift.append(str(legacy.relative_to(root)))
    if drift:
        print("Skill projection differs: " + ", ".join(drift))
        return 1
    print("Claude/Codex threat skill and routing scenarios match.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
